export default function LegalDocumentPage({ documentId }: { documentId: LegalDocumentId }) {
  const locale = readStoredLocale();
  const chrome = chromeCopy[locale as AppLocale];
  const document = legalDocuments[documentId];
  const seo = getPublicSeo(document.path as "/" | "/body" | "/privacy" | "/terms" | "/medical-disclaimer", locale);

  usePageSeo({
    title: seo.title,
    description: seo.description,
    path: document.path,
    locale,
    ogType: "article",
  });

  return (
    <div className="min-h-screen bg-[#02050c] text-slate-100">
      <div className="mx-auto max-w-5xl px-4 py-8 md:px-6 md:py-12">
        <div className="mb-8 flex flex-col gap-5 rounded-[28px] border border-white/10 bg-white/[0.03] p-6 shadow-[0_30px_100px_rgba(0,0,0,0.35)] backdrop-blur-xl md:p-8">
          <div className="flex flex-wrap items-center justify-between gap-3">
            <Link
              to="/"
              className="inline-flex items-center rounded-full border border-white/15 px-4 py-2 text-sm text-slate-200 transition-colors hover:border-cyan-300 hover:text-cyan-200"
            >
              {chrome.back}
            </Link>
            <div className="text-sm uppercase tracking-[0.2em] text-cyan-300">{chrome.title}</div>
          </div>

          {chrome.note ? <p className="text-sm text-slate-300">{chrome.note}</p> : null}

          <div className="flex flex-wrap gap-2">
            {(Object.keys(navigationLabels) as LegalDocumentId[]).map((id) => {
              const isActive = id === documentId;
              return (
                <Link
                  key={id}
                  to={
                    id === "privacy"
                      ? "/privacy"
                      : id === "terms"
                        ? "/terms"
                        : "/medical-disclaimer"
                  }
                  className={`rounded-full px-4 py-2 text-sm font-medium transition ${
                    isActive
                      ? "bg-gradient-to-r from-cyan-400 to-emerald-400 text-slate-950"
                      : "border border-white/15 text-slate-300 hover:border-cyan-300 hover:text-cyan-200"
                  }`}
                >
                  {navigationLabels[id]}
                </Link>
              );
            })}
          </div>
        </div>

        <article className="rounded-[32px] border border-white/10 bg-slate-950/70 p-6 shadow-[0_40px_120px_rgba(0,0,0,0.45)] md:p-10">
          <p className="text-xs uppercase tracking-[0.22em] text-cyan-300">{document.meta}</p>
          <h1 className="mt-4 text-3xl font-semibold md:text-4xl">{document.title}</h1>
          {document.intro ? <p className="mt-5 text-base text-slate-300">{document.intro}</p> : null}

          <div className="mt-8 space-y-8">
            {document.sections.map((section, index) => (
              <section key={`${section.title}-${index}`}>
                <h2 className="text-xl font-semibold text-white">{section.title}</h2>
                {section.paragraphs?.map((paragraph) => (
                  <p key={paragraph} className="mt-3 leading-7 text-slate-300">
                    {paragraph}
                  </p>
                ))}
                {section.bullets?.length ? (
                  <ul className="mt-4 space-y-2 pl-5 text-slate-300 marker:text-cyan-300 list-disc">
                    {section.bullets.map((bullet) => (
                      <li key={bullet} className="leading-7">
                        {bullet}
                      </li>
                    ))}
                  </ul>
                ) : null}
              </section>
            ))}
          </div>

          {document.closing ? (
            <p className="mt-10 border-t border-white/10 pt-6 text-sm text-slate-400">{document.closing}</p>
          ) : null}
        </article>
      </div>
    </div>
  );
}
